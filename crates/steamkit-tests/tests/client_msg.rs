/// Unwraps a library `Result`, or fails the test with a descriptive message.
fn or_fail<T>(result: Result<T, SteamError>, what: &str) -> T {
    match result {
        Ok(value) => value,
        Err(error) => panic!("{what}: {error}"),
    }
}

