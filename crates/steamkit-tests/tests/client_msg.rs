/// Parses the raw test vector into a packet message.
fn build_struct_msg() -> Box<dyn IPacketMsg> {
    let client = SteamClient::new();

    match client.cm_client().get_packet_msg(STRUCT_MSG_DATA.to_vec()) {
        Some(packet) => packet,
        None => panic!("the struct message test vector must parse as a packet message"),
    }
}

#[test]
fn payload_reader_reads_null_term_string() {
    let packet = build_struct_msg();
    let mut msg = or_fail(
        ClientMsg::<MsgClientChatEnter>::from_packet(packet.as_ref()),
        "the struct message test vector must parse as a ClientMsg<MsgClientChatEnter>",
    );

    let chat_name = or_fail(
        msg.payload_mut().read_null_term_string(),
        "reading the null terminated chat name must succeed",
    );

    assert_eq!("Saxton Hell", chat_name);
}

#[test]
fn payload_reader_does_not_overflow_past_null_term_string() {
    let packet = build_struct_msg();
    let mut msg = or_fail(
        ClientMsg::<MsgClientChatEnter>::from_packet(packet.as_ref()),
        "the struct message test vector must parse as a ClientMsg<MsgClientChatEnter>",
    );

    let chat_name = or_fail(
        msg.payload_mut().read_null_term_string(),
        "reading the null terminated chat name must succeed",
    );

    assert_eq!("Saxton Hell", chat_name);

    let next_byte = or_fail(
        msg.payload_mut().read_byte(),
        "reading the next byte must succeed",
    );
    let m_byte = or_fail(
        msg.payload_mut().read_byte(),
        "reading the byte after the null terminator must succeed",
    );

    // next byte should be a null
    assert_eq!(0, next_byte);
    // and the one after should be the beginning of a MessageObject
    assert_eq!(b'M', m_byte);
}
